/**
 * Polymer Finder — curated engineering polymer dataset.
 *
 * Values are TYPICAL figures for a representative, unfilled, general-purpose
 * grade unless the `grade` field says otherwise. Real grades vary widely
 * (often ±20–50%), so treat these as a screening aid only and confirm with the
 * supplier datasheet and your own testing.
 *
 * Chemical resistance ratings assume room temperature, short-to-moderate
 * exposure and no applied stress. Stress-cracking under load can be much worse.
 *   E = excellent, G = good, F = fair / limited, P = poor / not recommended
 */

import { applyRefs } from './verified';

export type Rating = 'E' | 'G' | 'F' | 'P';
export type Compat = 'yes' | 'limited' | 'no';
export type Transparency = 'clear' | 'translucent' | 'opaque';
export type Family =
  | 'Commodity'
  | 'Engineering'
  | 'High-performance'
  | 'Fluoropolymer'
  | 'Elastomer';

export type ChemKey =
  | 'acids'
  | 'bases'
  | 'alcohols'
  | 'bleach'
  | 'oils'
  | 'ketones'
  | 'aromatics';

