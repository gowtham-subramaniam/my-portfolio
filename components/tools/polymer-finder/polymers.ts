export const RATING_LABELS: Record<Rating, string> = {
  E: 'Excellent',
  G: 'Good',
  F: 'Fair',
  P: 'Poor',
};

export interface Processing {
  /** Typical mold shrinkage, % (null = not molded, e.g. machined stock) */
  shrinkPct: [number, number] | null;
  /** Drying before processing: °C and hours (null = not normally required) */
  dryC: number | null;
  dryH: number | null;
  /** Melt temperature for thermoplastics, cure temperature for rubbers, °C */
  meltC: [number, number] | null;
  /** Mold (tool) temperature, °C */
  moldC: [number, number] | null;
  note?: string;
}

export interface Polymer {
  id: string;
  name: string;
  abbr: string;
  family: Family;
  structure: 'Amorphous' | 'Semi-crystalline' | 'Elastomer';
  /** Grade basis for the numbers below. */
  grade: string;
  density: number; // g/cm³
  tensileMPa: number; // tensile strength (yield or break)
  modulusGPa: number | null; // tensile modulus; null for elastomers
  elongationPct: number; // elongation at break
  hardness?: string; // Shore hardness (elastomers)
  hdtC: number | null; // HDT @ 1.8 MPa; null where not meaningful
  contUseC: number; // typical max continuous-use temperature
  tgC: number | null;
  tmC: number | null;
  waterAbsPct: number; // 24 h immersion
  transparency: Transparency;
  sterilization: { autoclave: Compat; gamma: Compat; eto: Compat };
  chem: Record<ChemKey, Rating>;
  ul94: string; // typical rating of the base grade
  /** UV / outdoor weathering resistance of an unstabilized natural grade (UV-stabilized or carbon-black grades are often much better) */
  uv: Rating;
  costTier: 1 | 2 | 3 | 4 | 5;
  medical: boolean; // medical / biocompatible grades commonly available
  food: boolean; // food-contact grades commonly available
  processes: string[];
  strengths: string[];
  limitations: string[];
  uses: string[];
  aka: string[]; // trade names and synonyms
  summary: string;
  processing: Processing;
  /** Design and manufacturing pitfalls engineers commonly run into */
  watchOuts: string[];
  /** Card values taken from the reference-grade datasheet (set by applyRefs), as display text */
  verified?: Partial<Record<import('./verified').VKey, string>>;
}

