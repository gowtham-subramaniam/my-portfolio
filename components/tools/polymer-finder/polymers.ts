/** Text that represents each polymer for the embedding model (kept short: MiniLM truncates long input). */
export function polymerDocText(p: Polymer): string {
  return [
    `${p.name} (${p.abbr}).`,
    p.family === 'Elastomer' ? 'Elastomer.' : `${p.family} ${p.structure.toLowerCase()} polymer.`,
    p.summary,
    `Strengths: ${p.strengths.join('; ')}.`,
    `Limitations: ${p.limitations.join('; ')}.`,
    `Typical uses: ${p.uses.join('; ')}.`,
    `Also known as: ${p.aka.join(', ')}.`,
  ].join(' ');
}

/** Fuller text for keyword search: includes watch-outs and processes, so queries like "warpage" or "SLS" hit. */
export function polymerKeywordText(p: Polymer): string {
  return [polymerDocText(p), p.watchOuts.join(' '), p.processes.join(' ')].join(' ');
}
