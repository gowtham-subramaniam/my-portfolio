/**
 * Reference grades: one named commercial grade (or, where no grade could be
 * opened, a supplier's stock-shape sheet) per material, with the values copied
 * from its datasheet. These values replace the generic card numbers, so every
 * number shown with a ✓ can be traced to the linked document.
 *
 * Rules: values are copied as published (psi and °F converted to MPa and °C).
 * Nothing is estimated. A property the datasheet does not give is left out,
 * and the card then shows the older typical value marked "unverified".
 */

export type Val = number | [number, number];

export interface Field {
  v: Val;
  /** Test standard / condition as stated on the datasheet */
  std: string;
  /** Value is a lower bound, e.g. "> 50 %" */
  atLeast?: boolean;
}

export interface Ref {
  grade: string;
  /** "grade" = named commercial grade; "stock" = supplier stock-shape sheet without a grade; "report" = compound test report */
  kind: "grade" | "stock" | "report";
  src: { label: string; url: string };
  density?: Field; // g/cm³
  tensile?: Field & { what: "yield" | "break" | "strength" }; // MPa
  modulus?: Field; // MPa
  elongation?: Field; // % at break
  hdt?: Field; // °C at 1.8 MPa
  tg?: Field; // °C
  tm?: Field; // °C
  water24h?: Field; // %, 24 h immersion only
  contUse?: Field; // °C, only where a UL 746B RTI or stated service temperature is published
  ul94?: { v: string; std: string };
  hardness?: { v: string; std: string };
  /** Strain at yield, %, where published (used for the snap-fit rule) */
  yieldStrain?: number;
  /** Other published values worth showing (as printed) */
  other?: string[];
  note?: string;
}

