export const lo = (v: Val) => (Array.isArray(v) ? v[0] : v);
export const fmtVal = (v: Val, unit: string, atLeast?: boolean) => {
  const s = Array.isArray(v) ? `${v[0]}–${v[1]}` : `${v}`;
  return `${atLeast ? "> " : ""}${s}${unit ? (unit === "%" ? " %" : ` ${unit}`) : ""}`;
};
